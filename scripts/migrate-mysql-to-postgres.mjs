import fs from 'node:fs'
import mysql from 'mysql2/promise'
import pg from 'pg'

const { Client } = pg

function loadEnv() {
  return Object.fromEntries(
    fs.readFileSync('.env', 'utf8')
      .split(/\r?\n/)
      .filter(line => line && !line.trim().startsWith('#') && line.includes('='))
      .map(line => {
        const index = line.indexOf('=')
        return [line.slice(0, index).trim(), line.slice(index + 1).trim()]
      })
  )
}

const quoteId = value => `"${String(value).replaceAll('"', '""')}"`
const columnId = value => quoteId(String(value).toLowerCase())

function postgresType(column) {
  const type = String(column.DATA_TYPE).toLowerCase()
  if (['tinyint', 'smallint'].includes(type)) return 'SMALLINT'
  if (['int', 'integer', 'mediumint'].includes(type)) return 'INTEGER'
  if (type === 'bigint') return 'BIGINT'
  if (['decimal', 'numeric'].includes(type)) {
    return column.NUMERIC_PRECISION
      ? `NUMERIC(${column.NUMERIC_PRECISION},${column.NUMERIC_SCALE || 0})`
      : 'NUMERIC'
  }
  if (type === 'float') return 'REAL'
  if (type === 'double') return 'DOUBLE PRECISION'
  if (type === 'varchar') return `VARCHAR(${column.CHARACTER_MAXIMUM_LENGTH || 255})`
  if (type === 'char') return `CHAR(${column.CHARACTER_MAXIMUM_LENGTH || 1})`
  if (['text', 'tinytext', 'mediumtext', 'longtext', 'enum', 'set'].includes(type)) return 'TEXT'
  if (['datetime', 'timestamp'].includes(type)) return 'TIMESTAMP'
  if (type === 'date') return 'DATE'
  if (type === 'time') return 'TIME'
  if (['blob', 'tinyblob', 'mediumblob', 'longblob', 'binary', 'varbinary'].includes(type)) return 'BYTEA'
  if (type === 'json') return 'JSONB'
  return 'TEXT'
}

function postgresDefault(column) {
  if (String(column.EXTRA || '').includes('auto_increment')) return ''
  const value = column.COLUMN_DEFAULT
  if (value === null || value === undefined) return ''
  const text = String(value)
  if (/^null$/i.test(text)) return ''
  if (/^current_timestamp(?:\(\))?$/i.test(text)) return ' DEFAULT CURRENT_TIMESTAMP'
  if (/^curdate(?:\(\))?$/i.test(text)) return ' DEFAULT CURRENT_DATE'
  if (/^-?\d+(?:\.\d+)?$/.test(text)) return ` DEFAULT ${text}`
  return ` DEFAULT '${text.replaceAll("'", "''")}'`
}

async function main() {
  const env = loadEnv()
  const source = await mysql.createConnection({
    host: env.DB_HOST,
    port: Number(env.DB_PORT || 3306),
    user: env.DB_USER,
    password: env.DB_PASSWORD,
    database: env.DB_NAME,
    dateStrings: false
  })

  const admin = new Client({ host: '127.0.0.1', port: 5432, user: 'postgres', database: 'postgres' })
  await admin.connect()
  const exists = await admin.query("SELECT 1 FROM pg_database WHERE datname = 'club_systems'")
  if (!exists.rowCount) await admin.query('CREATE DATABASE club_systems')
  await admin.end()

  const target = new Client({ host: '127.0.0.1', port: 5432, user: 'postgres', database: 'club_systems' })
  await target.connect()
  await target.query('DROP SCHEMA public CASCADE; CREATE SCHEMA public')

  const [tables] = await source.execute(
    `SELECT TABLE_NAME FROM information_schema.TABLES
      WHERE TABLE_SCHEMA = ? AND TABLE_TYPE = 'BASE TABLE' ORDER BY TABLE_NAME`,
    [env.DB_NAME]
  )

  const report = []
  for (const { TABLE_NAME: table } of tables) {
    const [columns] = await source.execute(
      `SELECT COLUMN_NAME, DATA_TYPE, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT, EXTRA,
              CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE, ORDINAL_POSITION
         FROM information_schema.COLUMNS
        WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY ORDINAL_POSITION`,
      [env.DB_NAME, table]
    )
    const [primaryRows] = await source.execute(
      `SELECT COLUMN_NAME FROM information_schema.KEY_COLUMN_USAGE
        WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? AND CONSTRAINT_NAME = 'PRIMARY'
        ORDER BY ORDINAL_POSITION`,
      [env.DB_NAME, table]
    )
    const primary = primaryRows.map(row => columnId(row.COLUMN_NAME))
    const definitions = columns.map(column => {
      const identity = String(column.EXTRA || '').includes('auto_increment') ? ' GENERATED BY DEFAULT AS IDENTITY' : ''
      const nullable = column.IS_NULLABLE === 'NO' ? ' NOT NULL' : ''
      return `${columnId(column.COLUMN_NAME)} ${postgresType(column)}${identity}${postgresDefault(column)}${nullable}`
    })
    if (primary.length) definitions.push(`PRIMARY KEY (${primary.join(', ')})`)
    await target.query(`CREATE TABLE ${quoteId(table)} (${definitions.join(', ')})`)

    const [indexes] = await source.execute(
      `SELECT INDEX_NAME, COLUMN_NAME, SEQ_IN_INDEX FROM information_schema.STATISTICS
        WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? AND NON_UNIQUE = 0 AND INDEX_NAME <> 'PRIMARY'
        ORDER BY INDEX_NAME, SEQ_IN_INDEX`,
      [env.DB_NAME, table]
    )
    const grouped = new Map()
    for (const index of indexes) {
      const values = grouped.get(index.INDEX_NAME) || []
      values.push(index.COLUMN_NAME)
      grouped.set(index.INDEX_NAME, values)
    }
    for (const [name, names] of grouped) {
      await target.query(`CREATE UNIQUE INDEX ${quoteId(`${table}_${name}`)} ON ${quoteId(table)} (${names.map(columnId).join(', ')})`)
    }

    const [rows] = await source.query(`SELECT * FROM ${quoteId(table).replaceAll('"', '`')}`)
    if (rows.length) {
      const names = columns.map(column => column.COLUMN_NAME)
      const insert = `INSERT INTO ${quoteId(table)} (${names.map(columnId).join(', ')}) VALUES (${names.map((_, index) => `$${index + 1}`).join(', ')})`
      for (const row of rows) await target.query(insert, names.map(name => row[name]))
    }
    for (const column of columns.filter(item => String(item.EXTRA || '').includes('auto_increment'))) {
      await target.query(
        `SELECT setval(pg_get_serial_sequence($1, $2), COALESCE((SELECT MAX(${columnId(column.COLUMN_NAME)}) FROM ${quoteId(table)}), 1), (SELECT COUNT(*) > 0 FROM ${quoteId(table)}))`,
        [table, String(column.COLUMN_NAME).toLowerCase()]
      )
    }
    report.push({ table, rows: rows.length })
  }

  await target.end()
  await source.end()
  console.log(JSON.stringify({ database: 'club_systems', tables: report.length, report }, null, 2))
}

main().catch(error => {
  console.error(error)
  process.exit(1)
})
