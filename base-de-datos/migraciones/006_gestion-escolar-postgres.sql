BEGIN;
CREATE TABLE IF NOT EXISTS solicitudes_constancia (
 id SERIAL PRIMARY KEY, alumno_id INTEGER NOT NULL REFERENCES alumnos(id), motivo TEXT NOT NULL,
 creado_por INTEGER NOT NULL REFERENCES usuarios(id), creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS pagos_escolares (
 id SERIAL PRIMARY KEY, alumno_id INTEGER NOT NULL REFERENCES alumnos(id), folio VARCHAR(100) NOT NULL UNIQUE,
 monto NUMERIC(12,2) NOT NULL CHECK(monto>=0), solicitud_id INTEGER UNIQUE REFERENCES solicitudes_constancia(id),
 verificado_por INTEGER NOT NULL REFERENCES usuarios(id), creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS adeudos_material (
 id SERIAL PRIMARY KEY, alumno_id INTEGER NOT NULL REFERENCES alumnos(id), descripcion TEXT NOT NULL,
 resuelto BOOLEAN NOT NULL DEFAULT FALSE, creado_por INTEGER NOT NULL REFERENCES usuarios(id), creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS autorizaciones_inscripcion (
 id SERIAL PRIMARY KEY, alumno_id INTEGER NOT NULL REFERENCES alumnos(id), periodo_id INTEGER NOT NULL REFERENCES periodos(id),
 autorizado_por INTEGER NOT NULL REFERENCES usuarios(id), motivo TEXT NOT NULL, creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(alumno_id, periodo_id));
COMMIT;
